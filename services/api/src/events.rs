//! Interaction events (architecture §8.4).
//!
//! Two different things happen when an event arrives:
//! - **Functional effects** always apply. `card_viewed` puts the card in the no-repeat ledger,
//!   because "never show me this again" is product behaviour, not tracking.
//! - **Analytics rows** are stored only if the reader has given personalisation consent.

use axum::{Json, extract::State, http::StatusCode};
use chrono::{DateTime, Utc};
use serde::Deserialize;
use serde_json::{Value, json};
use sqlx::PgConnection;
use uuid::Uuid;

use crate::{
    auth::CurrentUser,
    error::{ApiJson, AppError, AppResult},
    state::AppState,
};

/// Event types a client may send. `card_saved` and `dose_completed` are recorded by the
/// server as side effects of the saved/dose endpoints.
const CLIENT_EVENT_TYPES: &[&str] = &[
    "card_viewed",
    "card_liked",
    "card_shared",
    "source_opened",
    "connection_followed",
    "discover_entered",
];

pub struct AnalyticsEvent<'a> {
    pub id: Uuid,
    pub event_type: &'a str,
    pub card_id: Option<Uuid>,
    pub feed_mode: Option<&'a str>,
    pub session_id: Option<&'a str>,
    pub occurred_at: Option<DateTime<Utc>>,
}

impl<'a> AnalyticsEvent<'a> {
    /// An event generated by the server itself.
    pub fn server(event_type: &'a str, card_id: Option<Uuid>, feed_mode: Option<&'a str>) -> Self {
        Self {
            id: Uuid::new_v4(),
            event_type,
            card_id,
            feed_mode,
            session_id: None,
            occurred_at: None,
        }
    }
}

/// Store an analytics event if (and only if) the reader consented. Returns whether it was stored.
pub async fn record_analytics(
    conn: &mut PgConnection,
    user: &CurrentUser,
    event: AnalyticsEvent<'_>,
) -> AppResult<bool> {
    if !user.personalisation_consent {
        return Ok(false);
    }
    sqlx::query(
        "insert into user_event (id, user_id, event_type, card_id, card_version_id, feed_mode,
                                 session_id, occurred_at)
         values ($1, $2, $3, $4, (select active_version_id from card where id = $4), $5, $6,
                 coalesce($7, now()))
         on conflict (id) do nothing",
    )
    .bind(event.id)
    .bind(user.id)
    .bind(event.event_type)
    .bind(event.card_id)
    .bind(event.feed_mode)
    .bind(event.session_id)
    .bind(event.occurred_at)
    .execute(conn)
    .await?;
    Ok(true)
}

#[derive(Debug, Deserialize)]
pub struct EventIn {
    pub event_id: Uuid,
    pub event_type: String,
    pub card_id: Option<Uuid>,
    pub feed_mode: Option<String>,
    pub session_id: Option<String>,
    pub occurred_at: Option<DateTime<Utc>>,
}

pub async fn post_event(
    State(state): State<AppState>,
    user: CurrentUser,
    ApiJson(event): ApiJson<EventIn>,
) -> AppResult<(StatusCode, Json<Value>)> {
    if !CLIENT_EVENT_TYPES.contains(&event.event_type.as_str()) {
        return Err(AppError::BadRequest(format!(
            "event_type must be one of: {}",
            CLIENT_EVENT_TYPES.join(", ")
        )));
    }
    if let Some(mode) = &event.feed_mode
        && mode != "dose"
        && mode != "discover"
    {
        return Err(AppError::BadRequest("feed_mode must be `dose` or `discover`".into()));
    }
    if event.session_id.as_ref().is_some_and(|s| s.len() > 100) {
        return Err(AppError::BadRequest("session_id is too long".into()));
    }

    let mut tx = state.pool.begin().await?;
    if let Some(card_id) = event.card_id {
        let exists: bool = sqlx::query_scalar(
            "select exists (select 1 from card where id = $1 and lifecycle_state in ('published', 'withdrawn'))",
        )
        .bind(card_id)
        .fetch_one(&mut *tx)
        .await?;
        if !exists {
            return Err(AppError::not_found("card"));
        }
    }

    let mut marked_read = false;
    if event.event_type == "card_viewed" {
        let (Some(card_id), Some(mode)) = (event.card_id, event.feed_mode.as_deref()) else {
            return Err(AppError::BadRequest("card_viewed needs card_id and feed_mode".into()));
        };
        sqlx::query(
            "insert into read_card (user_id, card_id, feed_mode) values ($1, $2, $3)
             on conflict do nothing",
        )
        .bind(user.id)
        .bind(card_id)
        .bind(mode)
        .execute(&mut *tx)
        .await?;
        marked_read = true;
    }

    let stored = record_analytics(
        &mut tx,
        &user,
        AnalyticsEvent {
            id: event.event_id,
            event_type: &event.event_type,
            card_id: event.card_id,
            feed_mode: event.feed_mode.as_deref(),
            session_id: event.session_id.as_deref(),
            occurred_at: event.occurred_at,
        },
    )
    .await?;
    tx.commit().await?;

    Ok((
        StatusCode::ACCEPTED,
        Json(json!({ "accepted": true, "marked_read": marked_read, "stored_for_analytics": stored })),
    ))
}
